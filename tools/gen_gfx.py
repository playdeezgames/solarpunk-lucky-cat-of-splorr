#!/usr/bin/env python3
"""Packs the game's pictures from the Anvil world art/composters.json (all drawn by Claude in the
Anvil) and the DINOBYTE font (CC BY 4.0, by mby) into generated Odin: src/game/gfx.odin and
src/game/font.odin (do not hand-edit). Run: python3 -I tools/gen_gfx.py

Pictures are 16x16 Sweetie-16 palette indices, 0 meaning transparent. The renderer may swap colours
per draw (slimy greens, grey houses)."""
import json
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
world = json.load(open(os.path.join(ROOT, 'art/composters.json')))

# Order is the Gfx enum order in src/game/screen.odin; names are images in the "compost" tileset.
NAMES = ['green_peel', 'green_lettuce', 'green_grass', 'brown_leaf', 'brown_card', 'brown_twig',
         'compost_a', 'compost_b', 'compost_c', 'fork', 'barrow', 'cat', 'roof', 'wall', 'roof_solar',
         'roof_farm', 'vines', 'turbine', 'barrel', 'garden_bare', 'garden_bloom', 'sun']

ts = next(t['tileset'] for t in world['tilesets'] if t['name'] == 'compost')
W, H = ts['width'], ts['height']
assert (W, H) == (16, 16), (W, H)
images = {im['name']: im['bytes'] for im in ts['images']}

out = ["// Generated by tools/gen_gfx.py from art/composters.json (the Anvil). Do not hand-edit.",
       "// Drawn by Claude (an AI agent) in the Anvil for Composters of SPLORR!!.",
       "package game", "", f"GFX_COUNT :: {len(NAMES)}", "",
       "// 16x16 palette indices per picture, row by row; 0 is transparent.",
       f"GFX := [{len(NAMES)}][256]u8{{"]
for name in NAMES:
    b = images[name]
    px = []
    for byte in b:
        px += [byte >> 4, byte & 15]
    assert len(px) == 256, (name, len(px))
    out.append(f"\t{{ // {name}")
    for y in range(16):
        out.append("\t\t" + ", ".join(str(v) for v in px[y * 16:(y + 1) * 16]) + ",")
    out.append("\t},")
out.append("}\n")
open(os.path.join(ROOT, 'src/game/gfx.odin'), 'w').write("\n".join(out))

font = Image.open(os.path.join(ROOT, 'tools/data/dbyte_1x.png')).convert('RGBA')
assert font.size == (96, 128), font.size
glyphs = []
for code in range(256):
    cx, cy = (code % 16) * 6, (code // 16) * 8
    bits = 0
    for y in range(8):
        for x in range(6):
            if font.getpixel((cx + x, cy + y))[3] > 0:
                bits |= 1 << (y * 6 + x)
    glyphs.append(bits)
lines = ["// Generated by tools/gen_gfx.py from tools/data/dbyte_1x.png (unmodified). Do not hand-edit.",
         "// DINOBYTE bitmap font by mby, https://mby.itch.io/dinobyte, CC BY 4.0.",
         "package game", "", "// 6x8 glyphs, one u64 per code page 437 character; bit (row*6 + col) is lit.",
         "FONT := [256]u64{"]
for i in range(0, 256, 4):
    lines.append("\t" + ", ".join(f"0x{g:012X}" for g in glyphs[i:i + 4]) + ",")
lines.append("}\n")
open(os.path.join(ROOT, 'src/game/font.odin'), 'w').write("\n".join(lines))
print(f"{len(NAMES)} pictures, 256 glyphs")
